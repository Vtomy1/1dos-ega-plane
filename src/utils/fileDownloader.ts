/**
 * Safe Browser File Download Utilities
 */

export function downloadBinaryFile(buffer: Uint8Array, filename: string, mimeType: string = 'application/octet-stream') {
  // Use sliced ArrayBuffer to avoid SharedArrayBuffer / BlobPart type discrepancy
  const arrayBuffer = buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength) as ArrayBuffer;
  const blob = new Blob([arrayBuffer], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

